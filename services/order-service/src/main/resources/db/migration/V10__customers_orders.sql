-- order-service schema, part 1: customers, orders, order_items, order_status_history.
-- Portable SQL: PostgreSQL 16 and H2 in MODE=PostgreSQL. (V1..V8 = platform-common, V10+ = this service, V1000+ = seed.)

CREATE TABLE customers (
    id         UUID                     NOT NULL PRIMARY KEY,
    name       VARCHAR(200)             NOT NULL,
    email      VARCHAR(254)             NOT NULL,
    tier       VARCHAR(20)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_customers_email UNIQUE (email)
);

CREATE TABLE orders (
    id               UUID                     NOT NULL PRIMARY KEY,
    customer_id      UUID                     NOT NULL,
    customer_email   VARCHAR(254)             NOT NULL,   -- snapshot at order time (event payloads need it without a join)
    status           VARCHAR(32)              NOT NULL,
    status_reason    VARCHAR(1000),
    total_amount     DECIMAL(19, 2)           NOT NULL,
    currency         VARCHAR(3)               NOT NULL,
    ship_line1       VARCHAR(200)             NOT NULL,
    ship_city        VARCHAR(100)             NOT NULL,
    ship_postal_code VARCHAR(20)              NOT NULL,
    ship_country     VARCHAR(64)              NOT NULL,
    correlation_id   VARCHAR(64),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT                   NOT NULL DEFAULT 0,   -- optimistic locking
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);

CREATE TABLE order_items (
    id         UUID           NOT NULL PRIMARY KEY,
    order_id   UUID           NOT NULL,
    line_no    INTEGER        NOT NULL,
    product_id UUID           NOT NULL,
    sku        VARCHAR(64),                 -- price snapshot, filled when validation succeeds
    name       VARCHAR(200),
    quantity   INTEGER        NOT NULL,
    unit_price DECIMAL(19, 2),
    line_total DECIMAL(19, 2),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT uq_order_items_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_order_items_qty CHECK (quantity BETWEEN 1 AND 1000)
);

CREATE TABLE order_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    UUID                     NOT NULL,
    from_status VARCHAR(32),
    to_status   VARCHAR(32)              NOT NULL,
    reason      VARCHAR(1000),
    actor       VARCHAR(200)             NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_history_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);
