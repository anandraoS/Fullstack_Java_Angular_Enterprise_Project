-- order-service schema, part 2: saga bookkeeping and HTTP idempotency.

CREATE TABLE saga_instances (
    id                    UUID                     NOT NULL PRIMARY KEY,
    order_id              UUID                     NOT NULL,
    state                 VARCHAR(24)              NOT NULL,
    current_step          VARCHAR(32)              NOT NULL,
    attempts              INTEGER                  NOT NULL DEFAULT 0,
    last_error            VARCHAR(1000),
    reason                VARCHAR(32),             -- compensation reason: CANCELLATION | FULFILLMENT_FAILURE | EXPIRED
    reservation_id        UUID,                    -- learned from InventoryReserved (reconciliation input)
    reservation_released  BOOLEAN                  NOT NULL DEFAULT FALSE,
    fulfillment_started   BOOLEAN                  NOT NULL DEFAULT FALSE,
    version               BIGINT                   NOT NULL DEFAULT 0,
    started_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_saga_order UNIQUE (order_id),
    CONSTRAINT fk_saga_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);

CREATE TABLE saga_step_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saga_id     UUID                     NOT NULL,
    order_id    UUID                     NOT NULL,
    step        VARCHAR(32)              NOT NULL,
    status      VARCHAR(16)              NOT NULL,
    attempt     INTEGER                  NOT NULL,
    detail      VARCHAR(1000),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_step_log_saga FOREIGN KEY (saga_id) REFERENCES saga_instances (id) ON DELETE CASCADE
);

-- HTTP idempotency (POST /orders): unique per (customer scope, key); stores the request fingerprint and the
-- response snapshot so a replay returns the ORIGINAL response even if the order has progressed since.
CREATE TABLE idempotency_keys (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope           VARCHAR(64)              NOT NULL,
    idem_key        VARCHAR(64)              NOT NULL,
    request_hash    VARCHAR(64)              NOT NULL,
    order_id        UUID,
    response_status INTEGER,
    response_body   VARCHAR(50000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_idempotency_scope_key UNIQUE (scope, idem_key)
);
