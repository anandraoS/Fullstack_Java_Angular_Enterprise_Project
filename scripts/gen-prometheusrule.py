"""Generates infrastructure/kubernetes/monitoring/prometheusrule.yaml from observability/prometheus/rules/oms-alerts.yml.
Usage: python -I scripts/gen-prometheusrule.py
"""
import os

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
src = os.path.join(ROOT, "observability/prometheus/rules/oms-alerts.yml")
dst = os.path.join(ROOT, "infrastructure/kubernetes/monitoring/prometheusrule.yaml")

doc = yaml.safe_load(open(src, encoding="utf-8"))
out = {
    "apiVersion": "monitoring.coreos.com/v1",
    "kind": "PrometheusRule",
    "metadata": {
        "name": "oms-alerts",
        "labels": {"app.kubernetes.io/part-of": "oms", "release": "kube-prometheus-stack"},
    },
    "spec": {"groups": doc["groups"]},
}


class Dumper(yaml.SafeDumper):
    pass


def str_rep(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


Dumper.add_representer(str, str_rep)
header = "# GENERATED by scripts/gen-prometheusrule.py from observability/prometheus/rules/oms-alerts.yml. Do not edit by hand.\n"
with open(dst, "w", encoding="utf-8", newline="\n") as f:
    f.write(header + yaml.dump(out, Dumper=Dumper, sort_keys=False, width=200))
print("wrote", dst)
